let lang = localStorage.getItem('amy-lang') || 'en';
let active = null;

const get = (obj, path) => {
    return path.split('.').reduce(
        (current, key) => current?.[key],
        obj
    );
};

function card([icon, title, description]) {
    return `
        <article class="card reveal">
            <div class="icon">${icon}</div>
            <h3>${title}</h3>
            <p>${description}</p>
        </article>
    `;
}

function renderTeam() {
    const t = T[lang];
    const box = document.getElementById('profileCard');
    const letters = document.getElementById('teamLetters');

    letters.innerHTML = t.members.map((member, index) => `
        <button
            class="team-letter ${active === index ? 'active' : ''}"
            data-member="${index}"
        >
            ${member[0]}
        </button>
    `).join('');

    letters.classList.toggle(
        'has-active',
        active !== null
    );

    letters.querySelectorAll('[data-member]').forEach(button => {
        button.onclick = () => {
            const index = Number(button.dataset.member);

            active = active === index ? null : index;

            renderTeam();
        };
    });

    if (active === null) {
        box.innerHTML = '';
        return;
    }

    const member = t.members[active];

    box.innerHTML = `
        <div class="profile-card card">
            <div class="profile-avatar">${member[0]}</div>

            <div>
                <h3>${member[1]}</h3>

                <div class="role">
                    ${t.team.role}
                </div>

                <p class="muted">
                    ${t.team.experience}:
                    <b style="color:#C4B5FD">4 Years</b>
                </p>

                <p class="muted">
                    ${member[2]}
                </p>

                <small style="color:rgba(168,85,247,.55);font-weight:700">
                    ${t.team.skills}
                </small>

                <div class="skills">
                    ${skills.map(skill => `
                        <span class="tag">${skill}</span>
                    `).join('')}
                </div>
            </div>
        </div>
    `;
}

function observe() {
    const observer = new IntersectionObserver(
        entries => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('visible');
                }
            });
        },
        {
            threshold: 0.12
        }
    );

    document
        .querySelectorAll('.reveal:not(.observed)')
        .forEach(element => {
            element.classList.add('observed');
            observer.observe(element);
        });
}

